// Converts Natural Earth (public domain) coastline + populated places into a compact
// Kotlin source file. Usage: node tools/geo/convert.mjs <geojson dir>
// Coastlines: Douglas-Peucker simplified, quantised to 0.01°, zigzag-varint deltas, base64.
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
const out = path.resolve(import.meta.dirname, "../../shared/src/commonMain/kotlin/com/zain/holoos/geo/WorldData.kt");
const TOL = 0.06; // degrees

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const bytes = [];
const varint = (n) => { while (n >= 0x80) { bytes.push((n & 0x7f) | 0x80); n >>>= 7; } bytes.push(n); };
const zz = (n) => (n << 1) ^ (n >> 31);

const coast = JSON.parse(fs.readFileSync(path.join(dir, "ne_50m_coastline.geojson")));
let lines = 0, points = 0;
for (const f of coast.features) {
  const g = f.geometry;
  for (const raw of g.type === "LineString" ? [g.coordinates] : g.coordinates) {
    const s = simplify(raw, TOL);
    if (s.length < 2) continue;
    varint(s.length); lines++; points += s.length;
    let px = 0, py = 0;
    for (const [lon, lat] of s) {
      const x = Math.round(lon * 100), y = Math.round(lat * 100);
      varint(zz(x - px)); varint(zz(y - py)); px = x; py = y;
    }
  }
}
const b64 = Buffer.from(bytes).toString("base64");
const chunks = b64.match(/.{1,48000}/g);

const places = JSON.parse(fs.readFileSync(path.join(dir, "ne_50m_populated_places_simple.geojson")));
const cities = places.features.map((f) => f.properties)
  .filter((p) => p.pop_max >= 1500000 || p.adm0cap == 1)
  .sort((a, b) => b.pop_max - a.pop_max)
  .map((p) => `    WorldCity("${p.nameascii.replace(/"/g, "")}", "${(p.adm0name || "").replace(/"/g, "")}", ${p.latitude.toFixed(3)}f, ${p.longitude.toFixed(3)}f, ${p.pop_max}, ${p.adm0cap == 1})`);

const kt = `// GENERATED by tools/geo/convert.mjs from Natural Earth (public domain). Do not edit.
package com.zain.holoos.geo

internal object WorldData {
    /** ${lines} coastline polylines, ${points} points. See [Coastlines] for the format. */
    val coastBase64: String get() = ${chunks.map((c) => `"${c}"`).join(" +\n        ")}

    val cities: List<WorldCity> = listOf(
${cities.join(",\n")},
    )
}
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, kt);
console.log(`lines=${lines} points=${points} bytes=${bytes.length} b64=${b64.length} chunks=${chunks.length} cities=${cities.length}`);
